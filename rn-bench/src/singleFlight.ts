/**
 * 같은 일을 **한 번만** 시킨다 (§13.106)
 *
 * ★ 왜 따로 떼어 놨나 — 이게 **깨져도 조용한** 종류의 코드이기 때문이다.
 *   토큰 갱신이 두 번 돌아도 화면에는 아무 표도 안 난다. 그런데 Supabase 는
 *   `refresh_token` 을 **한 번 쓰면 바꿔 준다**: 첫 갱신이 옛 표를 무효로 만들어
 *   뒤따르는 갱신은 **죽은 표**로 물어보고 실패한다. 운이 나쁘면 세션이 끊긴다.
 *   지도를 열면 핀·상호·저장·집계가 **동시에** 나가므로, 만료된 토큰이면
 *   401 이 네 개 한꺼번에 온다 — 이 파일이 막는 것이 바로 그 넷이다.
 *
 * ★ **끝나면 잊는다.** 결과를 들고 있으면 다음 만료 때 옛 성공을 되돌려 주고,
 *   그러면 영영 갱신하지 않는다. 캐시가 아니라 **합류(join)** 다.
 */
export function singleFlight<T>(fn: () => Promise<T>): () => Promise<T> {
  let inflight: Promise<T> | null = null;
  return () => {
    if (!inflight) {
      /* ★ `finally` 로 지운다 — 실패해도 지워야 **다시 해 볼 수 있다.**
         성공에서만 지우면 한 번 실패한 뒤로 영영 그 실패를 돌려준다. */
      inflight = fn().finally(() => { inflight = null; });
    }
    return inflight;
  };
}
