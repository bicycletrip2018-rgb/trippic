/**
 * 줌 버튼이 **어디로 갈지** (§13.97 ⑤ · §13.105)
 *
 * ── 먼저, 이 기능의 근거를 정직하게 적는다 ──────────────────────────
 * §13.97 이 이걸 맨 뒤로 미루며 *"한 손 조작에 좋다는 것은 **추측**"* 이라고 적었다.
 * 그 말은 **아직 맞다.** 한 손으로 쓰는 사람이 얼마나 되는지 우리는 안 세어 봤다.
 *
 * 추측이 아닌 것은 따로 있다:
 *   ① **축소에는 한 손 길이 아예 없다.** 확대는 더블탭이라도 있지만, 축소 제스처는
 *      핀치든 두손가락탭이든 **전부 손가락 둘**이다. 취향 문제가 아니라 제스처
 *      집합의 사실이다.
 *   ② **핀치는 겨냥이 안 된다.** 이 세션에서 길거리 줌에서 전국으로 나가려고
 *      핀치를 세 번 했는데 전국을 지나쳐 **500km** 까지 갔다. 버튼은 한 번에
 *      **한 단계**라 몇 번 눌렀는지가 곧 얼마나 움직였는지다.
 *
 * ── 왜 정수로 맞추나 ────────────────────────────────────────────────
 * 이 지도는 **정수 줌에서 성격이 바뀐다**: 9 집계 · 13 전부 · 14 상호 · 15 표지 카드.
 * `+1` 만 하면 13.2 → 14.2 처럼 **문턱을 지나치기만** 하고 그 문턱에 서지는 못한다.
 * 정수로 맞추면 버튼이 *"상호가 켜지는 줌"* 에 **정확히 세워 준다** — 핀치로는
 * 못 하는 일이고, 네이버를 베껴서가 아니라 우리 지도에 문턱이 있어서 그렇다.
 */

/* ★ 아래로는 3 까지. `fitBox.zoomForBBox` 의 안전장치와 **같은 값**이다 —
   그보다 멀어지면 세계가 반복되고 시·군·구 집계가 뜻을 잃는다. */
export const Z_MIN = 3;
/* ★ 위로는 18 까지. `place-dot` 의 크기 보간이 18 에서 끝난다 — 그 위는 우리
   데이터가 **아무것도 더 말해 주지 않는** 배경 지도일 뿐이다. 핀치로는 더 갈 수
   있고 막지 않는다. 버튼은 **우리 지도가 말을 하는 범위**까지만 데려간다. */
export const Z_MAX = 18;

/* ★ 이만큼도 안 움직이면 **고장 난 버튼**으로 보인다. 13.99 에서 정수로만 맞추면
   0.01 만 움직여 화면이 그대로다 — 눌렀는데 아무 일도 안 난 것과 같다.
   그때는 한 단계를 더 간다. */
const DEAD = 0.15;

const clamp = (z: number) => Math.min(Z_MAX, Math.max(Z_MIN, z));

export function zoomIn(z: number): number {
  const up = Math.floor(z) + 1;
  return clamp(up - z < DEAD ? up + 1 : up);
}

export function zoomOut(z: number): number {
  const down = Math.ceil(z) - 1;
  return clamp(z - down < DEAD ? down - 1 : down);
}

/** 버튼을 **흐리게** 할지. 눌러도 아무 일 없는 버튼을 멀쩡히 두지 않는다 */
export const canZoomIn = (z: number) => z < Z_MAX;
export const canZoomOut = (z: number) => z > Z_MIN;
