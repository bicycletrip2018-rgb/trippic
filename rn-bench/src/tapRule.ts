/**
 * 손가락이 **무엇을 먼저 보는가** (§13.116)
 *
 * ── 왜 필요했나 ─────────────────────────────────────────────────
 * §13.61 이 정한 규칙: *"집계 줌에서만 지역 탭을 받는다. 확대된 상태에서도 받으면
 * **핀을 노린 손가락을 지역이 가로챈다.**"* 맞는 규칙이었다 — 그때는 집계 줌에
 * **누를 것이 지역밖에 없었다.**
 *
 * §13.104 가 그걸 깼다. **저장한 곳(금테 점)을 줌과 무관하게 늘 그리기로** 했고,
 * 그 이유가 *"저장한 곳은 멀리서 볼 때 가장 쓸모 있다"* 였다. 그래서 집계 줌에
 * **일부러 눈에 띄게 그려 놓고 누르면 지역으로 들어가는** 화면이 됐다 —
 * §13.98 이 고친 바로 그 모양이다(*"그려 놓고 손가락으로는 한 곳도 못 겨눈다"*).
 *
 * ── 왜 저장만 앞에 세우나 (재서 정했다) ──────────────────────────
 * 손가락 하나는 반지름 22pt(§13.98)를 차지한다. 지도 자리를 402×700 으로 잡고
 * 마커가 **화면의 몇 %를 가로채는지** 세어 보면:
 *
 * | | 가로채는 넓이 |
 * |---|---|
 * | 저장 10곳 | 5% |
 * | 저장 30곳 | 16% |
 * | 저장 50곳 | 27% |
 * | **핀 300개**(`api_pins_in_bbox` 상한) | **100%** |
 *
 * → 저장은 앞세워도 **지역을 누를 자리가 남고**, 핀은 앞세우면 **지역이 사라진다.**
 *   취향이 아니라 **개수의 차이**다. 그래서 저장만 앞에 선다.
 *
 * ★ 그래도 **끝이 있다.** 저장이 계속 늘면 언젠가 핀과 같은 꼴이 된다 —
 *   `SAVE_FIRST_MAX` 를 넘으면 **앞세우지 않는다.** 한도 없이 두면 많이 저장한
 *   사용자만 지역 이동을 잃고, 그 사람은 **왜 안 되는지 영영 모른다.**
 */
import { Z_REGION } from "./fitBox";

/* 60곳이면 화면의 32% — 지역을 누를 자리가 2/3 남는다. 그 위로는 안 앞세운다.
   ★ §13.103 이 *"쉰 개가 넘는 사람이 실제로 생긴 다음"* 폴더를 보자고 적어 뒀다.
     그 언저리를 넘어가면 이 화면도 다시 봐야 한다는 뜻이기도 하다. */
export const SAVE_FIRST_MAX = 60;

/** 집계 줌에서 앞세우는 것 — **내가 찜한 것**뿐이다 */
const SAVED = ["save-dot", "save-label"];
/** 확대된 줌에서는 전부 본다(§13.98 이 정한 그대로, 저장이 더해졌다) */
const ALL = ["pin-dot", "place-label", "place-dot", "save-dot", "save-label"];

/**
 * 이 줌에서 손가락이 **먼저** 볼 레이어들.
 * 빈 배열이면 볼 것이 없다 — 바로 지역으로 간다.
 */
export function tapLayers(zoom: number, saveCount: number): string[] {
  if (zoom >= Z_REGION) return ALL;
  return saveCount > 0 && saveCount <= SAVE_FIRST_MAX ? SAVED : [];
}

/**
 * 마커를 **못 맞혔을 때** 지역으로 들어가도 되는가.
 * ★ 이것이 §13.61 의 규칙 그대로다 — 바뀐 것은 *"지역이 **먼저**"* 가
 *   *"지역이 **나중**"* 이 된 것뿐이다. 지역은 **배경**이고 마커는 **앞**이다.
 */
export const regionFallback = (zoom: number) => zoom < Z_REGION;
