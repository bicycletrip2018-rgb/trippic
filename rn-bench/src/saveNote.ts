/**
 * 저장한 곳 카드가 **한 줄로 뭐라고 말할지** (§13.103)
 *
 * ★ 왜 함수로 떼어 놨나 — **순서가 규칙**이기 때문이다. JSX 안의 삼항 세 개로
 *   두면 나중에 누가 줄을 바꿔 써도 아무 일도 안 일어나고, 그러면 문 닫은 곳이
 *   `10.03 저장` 으로 조용히 내려간다. 떼어 놓으면 빗장을 걸 수 있다.
 *
 * 순서의 이유:
 *   ① **닫힘** — 모르고 찾아가면 그날 하루가 날아간다. 저장한 날짜보다 급하다
 *   ② **다녀옴** — 저장 목록은 할 일 목록처럼 읽힌다. 이미 한 일을
 *      안 알려 주면 두 번 간다
 *   ③ 저장한 날 — 셋 중 가장 안 급한 것. 그래서 맨 뒤다
 *
 * ★ 셋을 **한 줄에 겹쳐 쓰지 않는다.** 카드 한 줄이 좁아서가 아니라,
 *   `문 닫음 · 이미 다녀온 곳 · 10.03 저장` 은 읽는 사람에게 아무 할 일도
 *   주지 않기 때문이다. 가장 급한 하나만 말한다.
 */
export type SaveNoteInput = {
  closed: boolean;
  been: boolean;
  /** ISO 문자열. `2026-10-03T...` */
  saved_at: string;
};

export function saveNote(x: SaveNoteInput): string {
  if (x.closed) return "문 닫았다고 신고된 곳";
  if (x.been) return "이미 다녀온 곳";
  return `${x.saved_at.slice(0, 10).replace(/-/g, ".")} 저장`;
}
