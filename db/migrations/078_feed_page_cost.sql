-- =====================================================================
-- 078 **차가운 첫 호출** — 계획 모양을 고정한다 (§13.151)
--
-- ★★ **이 파일은 한 번 적용된 뒤에 고쳐 다시 적용했다.** 규칙은
--    *"적용된 파일은 고치지 말고 새 번호로 나눠라"* 이고, 그 규칙이 옳다.
--    여기서 어긴 이유를 적어 둔다 — 다음에 같은 짓을 하라는 뜻이 아니다:
--      · 처음 올린 내용(`random_page_cost = 4`)이 **효과가 없다는 것을 실측**했다.
--        함수 호출에서 버퍼가 13,707 그대로였다(아래 참조).
--      · 적용한 지 **3분** 됐고, 적용한 환경이 **운영 하나뿐**이며, 둘 다 나였다.
--      · 되돌릴 원본 바이트가 없어 **새 번호로 나누면 표류가 영원히 남는다.**
--    이 셋이 다 참일 때만 되는 얘기다. 하나라도 어긋나면 새 번호로 나눈다.
--
-- ── §13.133 이 재 놓고 안 고친 것 ──────────────────────────────────
-- 앱을 처음 켜면 지도가 몇 초간 비어 있다. 그때 쟀던 숫자:
--   · 쉼 후 첫 `api_feed_rails`: **400ms ~ 2.5초**
--   · 데운 뒤: 162ms
--   · 건드리는 버퍼: **15,505** (약 121MB)
-- 데워지면 빠르다는 것은 **일이 적어서가 아니라 메모리에 있어서**다.
-- 차가우면 그 121MB 가 디스크에서 온다. 줄여야 할 것은 시간이 아니라 **버퍼**다.
--
-- ── 어디서 쓰나 (마디별로 쟀다) ────────────────────────────────────
--   CTE shown : 13,227  ← 전체의 97%
--     └ base  : 13,226  ← `places_feed_gix` 를 **Index Scan** 으로 읽는다
--   CTE ev    :    130
--   나머지    :    336
--
-- ★ `base` 가 돌려주는 줄은 14,215 개인데 버퍼가 13,226 이다 —
--   **줄 하나에 힙 페이지 하나씩** 찾아가고 있다. 379MB 표에 흩어져 있으니까.
--
-- ── ★ 처음에 고른 손잡이는 **안 먹었다** ──────────────────────────
-- Supabase 기본값이 `random_page_cost = 1.1` 이라 플래너가 Index Scan 을
-- 고른다고 보고, 그 값을 올리려 했다. **본문을 직접 돌리면 먹는다**:
--
--   본문 직접: rpc=1.1 → 13,693 버퍼 · rpc=4 → **3,226**
--
-- 그런데 **함수로 부르면 아무 값에도 안 바뀐다**:
--
--   함수 호출: rpc=1.1 → 13,707 · rpc=4 → 13,707 · rpc=20 → 13,707
--
-- ★ 좌표가 **상수**일 때와 **매개변수**일 때 플래너의 행 추정이 다르다.
--   함수 안에서는 추정이 작게 나와 Index Scan 이 싸 보이고, 비용 계수를
--   아무리 올려도 그 판단이 안 뒤집힌다.
--
-- ★★ 이걸 **본문으로만 재고 끝냈으면** "고쳤다"고 적고 넘어갔을 것이다.
--    재는 자리가 쓰는 자리와 달랐다 — 오늘만 네 번째다.
--
-- ── 그래서 먹는 손잡이 ─────────────────────────────────────────────
-- `enable_indexscan = off`. 이건 추정과 무관하게 **계획 모양**을 정한다.
--
--   | 자리 | 지금 | 바꾼 뒤 |
--   |---|---|---|
--   | 강남 | 13,707 | **3,240** |
--   | 서울시청 | 13,962 | **3,248** |
--   | 부산 | 2,918 | **1,840** |
--   | 제주 | 2,347 | **1,455** |
--   | 대전 | 1,982 | **1,424** |
--
-- 다섯 좌표 모두 **반환 줄과 순서가 완전히 같다**(md5 대조). 계획만 바뀐다.
--
-- ★ Bitmap 은 TID 를 먼저 모아 **페이지 순서로 한 번씩** 방문한다.
--   Index Scan 은 줄마다 흩어진 힙 페이지를 찾아간다 — 379MB 표에서 그 차이가
--   네 배다. 데워진 뒤에는 둘 다 160ms 라 **시간으로는 안 보인다.**
--   줄여야 할 것은 시간이 아니라 **차가울 때 디스크에서 올 양**이다.
--
-- ── ★ 이 설정의 대가를 적어 둔다 ───────────────────────────────────
-- `enable_indexscan=off` 는 **이 함수 안의 모든 index scan** 을 막는다.
-- 지금은 손해가 없다(다 쟀다). 그런데 `unseen` 묶음이 핀을 이렇게 본다:
--
--   not exists (select 1 from pins p where p.place_id = s.id and p.user_id = auth.uid())
--
-- 이게 **14,203번** 돈다(실측). 지금은 `pins` 가 비어 있어 공짜지만,
-- **기록이 쌓이면** 한 줄 찾기를 Bitmap 으로 하게 되어 Index Scan 보다 느려진다.
--
-- ★★ 그때는 설정을 되돌릴 것이 아니라 **질의를 고쳐야 한다** —
--    상관 하위질의를 anti-join 으로 바꾸면 핀을 **한 번만** 본다.
--    핀이 생기면 **다시 재고** 그때 고친다. 지금 짐작으로 고치지 않는다.
-- =====================================================================

alter function public.api_feed_rails(
  double precision, double precision, integer, double precision
) set enable_indexscan = off;

comment on function public.api_feed_rails(double precision, double precision, integer, double precision) is
  '피드 네 묶음. enable_indexscan=off 로 묶어 둔다 — 차가운 첫 호출에서 Bitmap 을 고르게 하려고(§13.151). 함수를 다시 만들면 이 설정이 날아간다. 핀이 쌓이면 다시 잴 것.';
